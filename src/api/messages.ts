const HAS_PERSIAN = /[؀-ۿ]/;
/** Persian text for a message from the host (Persian messages pass through unchanged). */
export function faMessage(message: string, status?: number): string {
  // "«name»: reason": the reason is translated, the name stays.
  const wrapped = message.match(/^(«.*?»):\s*(.+)$/s);
  if (wrapped && !HAS_PERSIAN.test(wrapped[2])) return `${wrapped[1]}: ${faMessage(wrapped[2], status)}`;
  if (HAS_PERSIAN.test(message)) return message;
  for (const [re, fa] of RULES) {
    const m = message.match(re);
    if (m) return typeof fa === 'function' ? fa(m) : fa;
  }
  return statusMessage(status);
}

/** What a status means when the host said nothing we can show. */
export function statusMessage(status?: number): string {
  switch (status) {
    case 400: return 'درخواست معتبر نیست؛ اطلاعات واردشده را بررسی کنید.';
    case 401: return 'برای این کار باید وارد شوید.';
    case 403: return 'اجازه‌ی این کار را ندارید.';
    case 404: return 'مورد پیدا نشد.';
    case 409: return 'این مورد هم‌زمان توسط کس دیگری تغییر کرده است؛ صفحه را تازه کنید.';
    case 413: return 'حجم درخواست یا فایل از حد مجاز بیشتر است.';
    case 429: return 'تعداد درخواست‌ها زیاد است؛ کمی صبر کنید و دوباره تلاش کنید.';
    case 0: return 'اتصال به سرور برقرار نشد؛ اینترنت یا سرور را بررسی کنید.';
    default: return status && status >= 500 ? 'خطای سرور؛ کمی بعد دوباره تلاش کنید.' : `خطا (${status ?? ''})`;
  }
}
